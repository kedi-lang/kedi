#!/usr/bin/env python3
"""Mirror the Kedi documentation into references/docs/ for offline use.

    python scripts/sync_docs.py [--docs PATH]      # rewrite references/docs/ and docs.md
    python scripts/sync_docs.py --check            # exit 1 if either is stale

The mirror keeps the source layout, so relative links work unchanged. Pages are copied
verbatim; only assets a page links to are copied. references/docs.md is an index generated
from page titles; it lives outside the mirror because docs/index.md already exists and
INDEX.md would collide with it on case-insensitive file systems.
"""

from __future__ import annotations

import argparse
import filecmp
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFERENCES = ROOT / "references"
DEFAULT_DOCS = ROOT.parents[2] / "kedi-docs" / "docs"
LINK = re.compile(r"\]\(([^)#\s]+)")


def build(docs: Path, references: Path) -> None:
    out = references / "docs"
    pages = sorted(docs.rglob("*.md"))
    if not pages:
        raise SystemExit(f"No documentation pages under {docs}")
    sections: dict[str, list[tuple[str, str]]] = {}
    for page in pages:
        rel = page.relative_to(docs)
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        text = page.read_text(encoding="utf-8")
        target.write_text(text, encoding="utf-8")
        for link in LINK.findall(text):
            if "://" in link or link.endswith(".md"):
                continue
            asset = (page.parent / link).resolve()
            if asset.is_file() and docs.resolve() in asset.parents:
                dest = out / asset.relative_to(docs.resolve())
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(asset, dest)
        title = next(
            (line[2:].strip() for line in text.splitlines() if line.startswith("# ")), rel.stem
        )
        section = rel.parts[0] if len(rel.parts) > 1 else "overview"
        sections.setdefault(section, []).append((title, rel.as_posix()))
    lines = [
        "# Kedi documentation index",
        "",
        "Generated by `scripts/sync_docs.py` from `kedi-docs/docs`; do not edit. Read one page at a time.",
        "",
    ]
    for section in sorted(sections):
        lines += [f"## {section}", "", "| Page | File |", "| --- | --- |"]
        lines += [f"| {title} | [{rel}](docs/{rel}) |" for title, rel in sections[section]]
        lines.append("")
    (references / "docs.md").write_text("\n".join(lines), encoding="utf-8")


def differences(left: Path, right: Path) -> list[str]:
    def walk(cmp: filecmp.dircmp, prefix: str) -> list[str]:
        out = [f"only in docs: {prefix}{n}" for n in cmp.left_only]
        out += [f"stale mirror file: {prefix}{n}" for n in cmp.right_only]
        out += [f"changed: {prefix}{n}" for n in cmp.diff_files]
        for name, sub in cmp.subdirs.items():
            out += walk(sub, f"{prefix}{name}/")
        return out

    return walk(filecmp.dircmp(left, right), "") if right.exists() else ["mirror missing"]


def main() -> int:
    cli = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    cli.add_argument("--docs", type=Path, default=DEFAULT_DOCS)
    cli.add_argument("--check", action="store_true")
    args = cli.parse_args()
    if not args.check:
        shutil.rmtree(REFERENCES / "docs", ignore_errors=True)
        build(args.docs, REFERENCES)
        print(f"Mirrored {args.docs} -> {REFERENCES / 'docs'}")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp)
        build(args.docs, fresh)
        problems = differences(fresh / "docs", REFERENCES / "docs")
        index = REFERENCES / "docs.md"
        if not index.exists() or index.read_bytes() != (fresh / "docs.md").read_bytes():
            problems.append("changed: docs.md (index)")
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print("Skill docs mirror is stale; run scripts/sync_docs.py.", file=sys.stderr)
        return 1
    print("Skill docs mirror matches kedi-docs.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
